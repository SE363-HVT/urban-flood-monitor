# -*- coding: utf-8 -*-
with open('scripts/build_phase3_batch25.py', 'r', encoding='utf-8') as f:
    c = f.read()

# 2413: [([0], [7, 8], 'NEG')] -> [([0], [8, 9], 'NEG')]
c = c.replace("[([0], [7, 8], 'NEG')]", "[([0], [8, 9], 'NEG')]")

# 2432: [([9, 10], [11, 12], 'POS')] -> [([10, 11], [12, 13], 'POS')]
c = c.replace("[([9, 10], [11, 12], 'POS')]", "[([10, 11], [12, 13], 'POS')]")

# 2433: [([4, 5], [11, 12], 'NEG')] -> [([4, 5], [13, 14], 'NEG')]
c = c.replace("[([4, 5], [11, 12], 'NEG')]", "[([4, 5], [13, 14], 'NEG')]")

# 2439: [([7, 8, 9, 10], [16, 17, 18, 19, 20], 'NEG'), ([12, 13, 14], [16, 17, 18, 19, 20], 'NEG')]
#    -> [([8, 9, 10, 11], [17, 18, 19, 20, 21], 'NEG'), ([13, 14, 15], [17, 18, 19, 20, 21], 'NEG')]
old_2439 = "[([7, 8, 9, 10], [16, 17, 18, 19, 20], 'NEG'), ([12, 13, 14], [16, 17, 18, 19, 20], 'NEG')]"
new_2439 = "[([8, 9, 10, 11], [17, 18, 19, 20, 21], 'NEG'), ([13, 14, 15], [17, 18, 19, 20, 21], 'NEG')]"
c = c.replace(old_2439, new_2439)

# 2444: [([15], [6, 7], 'NEG')] -> [([17], [8, 9], 'NEG')]
c = c.replace("[([15], [6, 7], 'NEG')]", "[([17], [8, 9], 'NEG')]")

# 2470: [([3, 4], [7, 8, 9, 10, 11], 'POS')] -> [([3, 4], [8, 9, 10, 11, 12], 'POS')]
c = c.replace("[([3, 4], [7, 8, 9, 10, 11], 'POS')]", "[([3, 4], [8, 9, 10, 11, 12], 'POS')]")

# 2494: [([0], [6, 7], 'NEG')] -> [([0], [5, 6], 'NEG')]
c = c.replace("[([0], [6, 7], 'NEG')]", "[([0], [5, 6], 'NEG')]")

with open('scripts/build_phase3_batch25.py', 'w', encoding='utf-8') as f:
    f.write(c)

print("Batch 25 fixes applied!")
