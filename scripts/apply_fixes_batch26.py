# -*- coding: utf-8 -*-
with open('scripts/build_phase3_batch26.py', 'r', encoding='utf-8') as f:
    c = f.read()

# 2517: [([8, 9, 10], [5, 6], 'NEG')] -> [([17, 18, 19], [34, 35, 36], 'NEG')]
c = c.replace("[([8, 9, 10], [5, 6], 'NEG')]", "[([17, 18, 19], [34, 35, 36], 'NEG')]")

# 2539: [([0, 1, 2, 3], [7, 8, 9, 10], 'NEG')] -> [([0, 1, 2, 3], [8, 9, 10, 11], 'NEG')]
c = c.replace("[([0, 1, 2, 3], [7, 8, 9, 10], 'NEG')]", "[([0, 1, 2, 3], [8, 9, 10, 11], 'NEG')]")

# 2550: [([0, 1], [11, 12], 'NEG')] -> [([0, 1], [13, 14], 'NEG')]
c = c.replace("[([0, 1], [11, 12], 'NEG')]", "[([0, 1], [13, 14], 'NEG')]")

# 2557: [([5, 6, 7, 8], [11, 12], 'NEG')] -> [([6, 7, 8, 9], [14, 15], 'NEG')]
c = c.replace("[([5, 6, 7, 8], [11, 12], 'NEG')]", "[([6, 7, 8, 9], [14, 15], 'NEG')]")

# 2583: [([4, 5, 6, 7, 8], [14], 'NEG')] -> [([4, 5, 6, 7, 8, 9], [16], 'NEG')]
c = c.replace("[([4, 5, 6, 7, 8], [14], 'NEG')]", "[([4, 5, 6, 7, 8, 9], [16], 'NEG')]")

with open('scripts/build_phase3_batch26.py', 'w', encoding='utf-8') as f:
    f.write(c)

print("Batch 26 fixes applied!")
